#!/bin/bash

# Codex ↔ Claude Code Parallel Development Daily Sync
# Run at 19:00 every day to check for conflicts and synchronize changes

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VAULT_ROOT="$(dirname "$(dirname "$SCRIPT_DIR")")"

cd "$VAULT_ROOT" || exit 1

echo "============================================"
echo "🔄 Parallel Development Daily Sync"
echo "📅 $(date +'%Y-%m-%d %H:%M:%S')"
echo "============================================"
echo ""

# Step 1: Check for concurrent edits
echo "Step 1️⃣ Checking for concurrent edits..."
node scripts/ai_coordination/check_concurrent_edits.mjs
CONCURRENT_RESULT=$?

echo ""
echo "============================================"

# Step 2: Detect merge conflicts
echo "Step 2️⃣ Detecting Git merge conflicts..."
if git status --porcelain | grep -E '^\s*[UDA]'; then
  echo "⚠️  Git conflicts detected - listing:"
  git diff --name-only --diff-filter=U
else
  echo "✅ No Git merge conflicts"
fi

echo ""
echo "============================================"

# Step 3: Generate sync report
echo "Step 3️⃣ Generating AI sync report..."
node scripts/ai_coordination/generate_ai_sync_report.mjs
SYNC_RESULT=$?

echo ""
echo "============================================"

# Step 4: Auto-merge non-conflicting changes
echo "Step 4️⃣ Auto-merging non-conflicting changes..."

# Check if there are staged changes
if git diff --cached --quiet; then
  echo "✅ No staged changes to merge"
else
  echo "📝 Found staged changes - checking for conflicts..."

  # Try auto-merge
  if git merge --no-edit origin/main 2>/dev/null; then
    echo "✅ Auto-merge successful"
    git add -A
    git commit -m "chore: auto-sync Codex and Claude Code changes" \
      -m "Auto-generated by parallel_dev_daily_sync.sh" \
      -m "Co-Authored-By: Codex <codex@openai.com>" \
      -m "Co-Authored-By: Claude Code <claude@anthropic.com>"
  else
    echo "⚠️  Auto-merge failed - manual resolution required"
  fi
fi

echo ""
echo "============================================"

# Step 5: Generate final summary
echo "Step 5️⃣ Generating final summary..."

SUMMARY_FILE="tmp/parallel_dev_summary_$(date +'%Y-%m-%d').md"

cat > "$SUMMARY_FILE" << EOF
# Parallel Development Daily Summary

**Date:** $(date +'%Y-%m-%d %H:%M:%S')

## 📊 Status

| Check | Result |
|-------|--------|
| Concurrent Edits | $([ $CONCURRENT_RESULT -eq 0 ] && echo "✅ OK" || echo "⚠️ CONFLICTS DETECTED") |
| Merge Conflicts | ✅ Checked |
| Auto-merge | ✅ Completed |

## 📋 Next Steps

### For Codex:
- Continue implementation of Utomachi 100 store features
- Check technical_specs for any updates from Claude Code
- Update development_logs with today's progress

### For Claude Code:
- Update ナレッジベース with latest information
- Review conflict_manifest.json for unresolved conflicts
- Generate tomorrow's analysis proposals

## 🔔 Alerts

$(if [ $CONCURRENT_RESULT -ne 0 ]; then
  echo "- ⚠️ Concurrent edits detected - see concurrent_edits_$(date +'%Y-%m-%d').md"
else
  echo "- ✅ No alerts"
fi)

---

*Generated by scripts/ai_coordination/parallel_dev_daily_sync.sh*
EOF

echo "✅ Summary saved: $SUMMARY_FILE"
echo ""

# Final report
echo "============================================"
echo "✅ Daily sync complete"
echo "📁 Report: $SUMMARY_FILE"
echo "============================================"

exit 0
